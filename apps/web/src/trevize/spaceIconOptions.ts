const ICON_NAMES: ReadonlySet<string> = new Set(iconNames);

/** Whether a stored icon name is one this Lucide version can draw. */
export function isSpaceIconName(name: string): name is IconName {
  return ICON_NAMES.has(name);
}

export function filterSpaceIconNames(query: string): ReadonlyArray<IconName> {
  const normalized = query.trim().toLowerCase().replaceAll(/\s+/g, "-");
  if (!normalized) return SPACE_ICONS;
  return iconNames.filter((name) => name.includes(normalized)).slice(0, 96);
}

